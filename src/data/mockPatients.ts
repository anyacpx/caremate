// 6 to 12 hour simulated trend points for patient vital charts
export interface VitalTrendPoint {
  time: string;
  heartRate: number;
  spo2: number;
  bpSystolic: number;
  bpDiastolic: number;
  activityLevel: number; // 0 to 100
  respiratoryRate: number;
}

export const generateTrendData = (patient: Patient): VitalTrendPoint[] => {
  const isHighRisk = patient.status === 'critical' || patient.status === 'warning';
  const baseline = patient.baseline;
  const current = patient.vitals;

  const points: VitalTrendPoint[] = [];
  const hours = ['05:00', '06:00', '07:00', '08:00', '09:00', '09:30', '10:00', '10:15', '10:30', '10:45', '10:55'];
  
  hours.forEach((time, index) => {
    const fraction = index / (hours.length - 1);
    
    if (!isHighRisk) {
      // Normal patient with slight natural baseline oscillations
      const hr = Math.round(baseline.heartRateMin + (baseline.heartRateMax - baseline.heartRateMin) * 0.5 + Math.sin(index) * 3);
      const sp = Math.round(97 + Math.cos(index) * 1);
      const bpS = Math.round(122 + Math.sin(index) * 4);
      const bpD = Math.round(78 + Math.cos(index) * 3);
      const resp = Math.round(16 + Math.sin(index) * 1);
      const act = index > 2 ? Math.min(100, Math.round(40 + Math.sin(index * 0.7) * 30)) : 10;

      points.push({
        time,
        heartRate: hr,
        spo2: sp,
        bpSystolic: bpS,
        bpDiastolic: bpD,
        activityLevel: act,
        respiratoryRate: resp,
      });
    } else {
      // Deteriorating patient trend (like Kim, Sun-hee)
      // Earlier hours are normal, then divergence starts after 10:00 AM
      if (index < 6) {
        // Morning baseline
        points.push({
          time,
          heartRate: 72 + Math.round(Math.sin(index) * 3),
          spo2: 97 + Math.round(Math.cos(index) * 0.5),
          bpSystolic: 128 + Math.round(Math.sin(index) * 3),
          bpDiastolic: 78 + Math.round(Math.cos(index) * 2),
          activityLevel: 45 + Math.round(Math.sin(index) * 15),
          respiratoryRate: 16,
        });
      } else {
        // Divergence progressing towards current
        const prog = (index - 5) / (hours.length - 6);
        const hr = Math.round(74 + (current.heartRate - 74) * prog);
        const sp = Math.round(97 - (97 - current.spo2) * prog);
        const bpS = Math.round(130 + (current.bloodPressureSys - 130) * prog);
        const bpD = Math.round(80 + (current.bloodPressureDia - 80) * prog);
        const act = Math.max(0, Math.round(50 - (50 - 5) * prog));
        const resp = Math.round(16 + (current.respiratoryRate - 16) * prog);

        points.push({
          time,
          heartRate: hr,
          spo2: sp,
          bpSystolic: bpS,
          bpDiastolic: bpD,
          activityLevel: act,
          respiratoryRate: resp,
        });
      }
    }
  });

  return points;
};
